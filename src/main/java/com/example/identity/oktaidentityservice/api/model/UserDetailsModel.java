package com.example.identity.oktaidentityservice.api.model;

import com.okta.sdk.resource.model.UserStatus;
import io.swagger.v3.oas.annotations.media.Schema;
import lombok.*;

import java.time.OffsetDateTime;

@Getter
@EqualsAndHashCode(callSuper = true)
@ToString(callSuper = true)
public class UserDetailsModel extends UserModel {

    @Schema(description = "Unique userID generated by Okta")
    private final String userid;

    @Schema(description = "Current status of the user account")
    private final UserStatus status;

    @Schema(description = "Created Timestamp")
    private final OffsetDateTime created;

    @Schema(description = "Activated Timestamp")
    private final OffsetDateTime activated;

    @Schema(description = "Status Change Timestamp")
    private final OffsetDateTime statusChanged;

    @Schema(description = "Last Login Timestamp")
    private final OffsetDateTime lastLogin;

    @Schema(description = "Last Updated Timestamp")
    private final OffsetDateTime lastUpdated;

    @Schema(description = "Password Changed Timestamp")
    private final OffsetDateTime passwordChanged;


    @Builder
    public UserDetailsModel(String firstname, String lastName, String email, String userName, String userid, UserStatus status, OffsetDateTime created, OffsetDateTime activated, OffsetDateTime statusChanged, OffsetDateTime lastLogin, OffsetDateTime lastUpdated, OffsetDateTime passwordChanged) {
        super(firstname, lastName, email, userName);
        this.userid = userid;
        this.status = status;
        this.created = created;
        this.activated = activated;
        this.statusChanged = statusChanged;
        this.lastLogin = lastLogin;
        this.lastUpdated = lastUpdated;
        this.passwordChanged = passwordChanged;
    }

}
